window.getSpecialistDocUrl = function (slug, docId) {
  var spec = window.SPECIALISTS[slug];
  if (!spec) return null;
  var doc = spec.docs.find(function (d) { return String(d.id) === String(docId); });
  if (!doc) return null;
  var path = 'docs/specialists/' + slug + '/' + encodeURIComponent(doc.file);
  try {
    return new URL(path, document.baseURI || window.location.href).href;
  } catch (e) {
    return path;
  }
};
